#!/usr/bin/env node
// scripts/perf/check-baseline-docs.mjs — R2: canonical JSON ↔ Markdown table
// reconciliation. --check fails (exit 1) when the managed markdown tables,
// run ID/version, or numeric references drift from the canonical JSON; --write
// updates ONLY the explicitly-marked generated tables, never human conclusions.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(join(fileURLToPath(import.meta.url), "..", "..", ".."));
const BASELINE = join(ROOT, "docs", "implementation", "PERF-BASELINE.json");
const DECISION = join(ROOT, "docs", "implementation", "decisions", "PERFORMANCE-BASELINE.md");

const LCP_MARKER = "<!-- GENERATED by check-baseline-docs: LCP medians by page/profile -->";

/** The managed LCP table for this baseline (single source for check AND write). */
export function renderLcpTable(baseline) {
  const pages = baseline.pages ?? [];
  const lcpLines = pages
    .map((p) => {
      const d = p.profiles.desktop.lcp.medianMs;
      const m = p.profiles.mobileLowEnd.lcp.medianMs;
      const mark = d > 2500 || m > 2500 ? " ⚠" : "";
      return `| ${p.path} | ${d} | ${m} |${mark}|`;
    })
    .join("\n");
  return `${LCP_MARKER}\n\n| page | desktop LCP ms | mobileLowEnd LCP ms | notes |\n|---|---|---|---|\n${lcpLines}\n`;
}

/**
 * Replace the managed block in the decision doc with `table`.
 *
 * The managed block runs from the marker to the next `## ` heading / `---` rule
 * or the END OF FILE. A previous implementation used a `m`-flagged regex whose
 * `$` alternative matched end-of-LINE, so for the real document — where the
 * managed table is the last block in the file — `--write` inserted a SECOND
 * table next to the stale one instead of replacing it (observed 2026-09-15
 * while promoting the R4 baseline). The lookahead below uses `$(?![\s\S])`,
 * which only matches the true end of input.
 */
export function applyManagedTable(decisionMarkdown, table) {
  const re = new RegExp(`${LCP_MARKER}[\\s\\S]*?(?=\\n## |\\n---|$(?![\\s\\S]))`, "");
  if (re.test(decisionMarkdown)) return decisionMarkdown.replace(re, table);
  return `${decisionMarkdown}\n\n${table}\n`;
}

export function reconcile(baseline, decisionMarkdown) {
  const drift = [];
  const table = renderLcpTable(baseline);
  // The managed block ends at the next ## heading (any level) or end of
  // document. The lookahead matches the next `\n##`/`\n---` (or the end).
  const re = new RegExp(`${LCP_MARKER}[\\s\\S]*?(?=\\n## |\\n---)`, "");
  // If we didn't find a sentinel, fall back to matching to end of doc.
  const reEof = new RegExp(`${LCP_MARKER}[\\s\\S]*$`, "");
  const current =
    re.exec(decisionMarkdown)?.[0] ?? reEof.exec(decisionMarkdown)?.[0];
  if (current && current.trim() !== table.trim()) {
    drift.push({
      kind: "lcp-table",
      detail: "managed LCP table differs from canonical JSON",
    });
  }
  if (baseline.measuredAt && !decisionMarkdown.includes(baseline.measuredAt)) {
    drift.push({
      kind: "run-id",
      detail: `measuredAt ${baseline.measuredAt} missing from decision doc`,
    });
  }
  return { drift, table };
}

const isMain = process.argv[1] && process.argv[1].endsWith("check-baseline-docs.mjs");
if (isMain) {
  const write = process.argv.includes("--write");
  const baseline = JSON.parse(readFileSync(BASELINE, "utf8"));
  const decision = readFileSync(DECISION, "utf8");
  const { drift, table } = reconcile(baseline, decision);
  if (write) {
    writeFileSync(DECISION, applyManagedTable(decision, table));
    console.log(`[check-baseline-docs] --write: updated managed LCP table`);
  } else {
    if (drift.length > 0) {
      for (const d of drift)
        console.error(`[check-baseline-docs] DRIFT ${d.kind}: ${d.detail}`);
      process.exitCode = 1;
    } else {
      console.log("[check-baseline-docs] OK: docs in sync with canonical JSON");
    }
  }
}
