function sha256(s) {
  return createHash("sha256").update(s).digest("hex");
}
function fileSha256(p) {
  return sha256(readFileSync(p));
}

function run(cmd, args, opts = {}) {
  return execFileSync(cmd, args, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    ...opts,
  }).trim();
}

/**
 * Generate a candidate redirect include with the DELIVERED redirects CLI
 * (WP-12-validated) against an isolated content root. Returns the CLI stdout.
 * The content root is built by the drill with real schema-shaped synthetic
 * fixtures; the CLI is the delivered generation path, not a mirror.
 */
function generateRedirectsViaCli(outPath, contentRoot) {
  return run("node", [...REGISTER_ARGS, REDIRECTS_CLI, "--content", contentRoot, "--out", outPath], {
    env: { ...process.env, NODE_OPTIONS: "" },
  });
}

/**
 * Build a release dir with index.html + a manifest listing ALL files with
 * sha256 (the deploy entry validates the manifest fully — a manifest that
 * lists only index.html while assets exist would be rejected as incomplete).
 */
function makeRelease(releasesDir, name, files) {
  const d = join(releasesDir, name);
  mkdirSync(d, { recursive: true });
  for (const [rel, content] of Object.entries(files)) {
    mkdirSync(join(d, rel, ".."), { recursive: true });
    writeFileSync(join(d, rel), content);
  }
  const manifestFiles = [];
  const walk = (rel) => {
    for (const f of readdirSync(join(d, rel))) {
      const full = join(d, rel, f);
      const relPath = rel ? `${rel}/${f}` : f;
      if (statSync(full).isDirectory()) walk(relPath);
      else manifestFiles.push({ path: relPath, sha256: sha256(readFileSync(full)) });
    }
  };
  walk("");
  writeFileSync(join(d, "manifest.json"), JSON.stringify({ files: manifestFiles }, null, 2));
  return d;
}

/**
 * curl helper: returns { status, location, body }.
 * Parses the FIRST response block only — a 301 body is nginx's own HTML
 * redirect page, which must never be confused with a second response block.
 */
function curl(listen, path) {
  const [host, port] = listen.split(":");
  const out = execFileSync(
    "curl",
    ["-sk", "--max-time", "3", "-i", `https://${host}:${port}${path}`],
    { encoding: "utf8" },
  );
  const headerBlock = out.slice(0, out.search(/\r?\n\r?\n/));
  const m = headerBlock.match(/^HTTP\/\S+ (\d+)/m);
  const status = m ? Number(m[1]) : 0;
  const loc = (headerBlock.match(/^location: (.+)$/im) || [])[1] || "";
  const body = out.slice(out.search(/\r?\n\r?\n/) + 4);
  return { status, location: loc, body };
}

/** 301 Location may be absolute (https://host:port/x) — normalize to a path. */
function locPath(location) {
  return location.replace(/^https?:\/\/[^/]+/, "");
}

/**
 * Follow a 301 chain (max 3 hops) and return the FINAL response. Proves the
 * redirect destination resolves to SERVABLE content, not just a Location
 * string (R7 finding). nginx serves directory canonicals via a slash 301.
 */
function followToContent(listen, path) {
  let cur = path;
  for (let hop = 0; hop < 3; hop++) {
    const r = curl(listen, cur);
    if (r.status !== 301) return r;
    cur = locPath(r.location);
  }
  return { status: 0, body: "(too many redirect hops)", location: "" };
}

/**
 * Wait for a reload to take effect by its OBSERVABLE behavior. `nginx -s
 * reload` signals the master, which spawns a NEW worker with the new
 * configuration and lets the OLD worker drain. Requests issued right after
 * the signal can still hit the old worker (the reload race observed in this
 * drill). Instead of chasing PIDs, poll the real HTTP behavior.
 */
function waitForBehavior(listen, path, expectStatus, timeoutMs = 5000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    const r = curl(listen, path);
    if (r.status === expectStatus) return r;
    execFileSync("/bin/sh", ["-c", "sleep 0.05"], { stdio: "ignore" });
  }
  const last = curl(listen, path);
  throw new Error(
    `reload behavior did not settle: expected ${expectStatus} for ${path}, last=${last.status} ${last.location || ""}`,
  );
}

/**
 * Worker set via PPID lineage (R8/M1, identity-checked R9/M2): children of
 * THIS master whose command is the real nginx worker process
 * (`nginx: worker process`), not just any descendant containing "nginx".
 * The recorded PID must be verified by identity before it is ever signalled.
 */
function workerPids(master) {
  const out = execFileSync("/bin/ps", ["-axo", "pid=,ppid=,command="], { encoding: "utf8" });
  const res = [];
  for (const line of out.split("\n")) {
    const m = line.match(/^\s*(\d+)\s+(\d+)\s+(.*)$/);
    if (!m) continue;
    // macOS ps prints "nginx: worker process"; some builds truncate to
    // "nginx: worker" — accept both, still excluding non-worker nginx lines.
    if (Number(m[2]) === master && /nginx: worker( process)?$/.test(m[3].trim())) res.push(Number(m[1]));
  }
  return res;
}

/**
 * PID identity check (R9/M2): true only while `pid` exists AND its command
 * still names an nginx master/worker — guards every signal against killing a
 * recycled PID belonging to another process or another nginx instance.
 */
function pidIsOurs(pid) {
  // pidFileRef is set by the drill once its scratch layout exists; identity
  // is confirmed against THIS instance's pid file, not a compile-time path.
  if (typeof pidFileRef !== "function") return false;
  if (!pid) return false;
  try {
    process.kill(pid, 0); // existence check (no signal for 0)
  } catch {
    return false; // gone
  }
  let cmd = "";
  try {
    const out = execFileSync("/bin/ps", ["-p", String(pid), "-o", "command="], { encoding: "utf8" });
    cmd = out.trim();
  } catch {
    return false; // vanished between kill(0) and ps
  }
  // The pid file belongs to THIS instance's conf; its master command embeds
  // the binary and (on macOS) no conf path — so require an nginx master AND
  // that the recorded master PID still matches the pid file when available.
  if (!/nginx: master process/.test(cmd)) return false;
  try {
    const recorded = Number(readFileSync(pidFileRef(), "utf8").trim());
    return recorded === pid;
  } catch {
    return false; // pid file unreadable/gone — cannot confirm identity
  }
}
/** Hoisted indirection so the module-level identity check can reach the
 *  drill's pid file path (set in main() before nginx starts). */
let pidFileRef = null;

async function main() {
  const args = process.argv.slice(2);
  let scratch = join(REPO_ROOT, "tests", "tmp", "nginx", "drill");
  let listen = DEFAULT_LISTEN;
  let nginxBin = process.env.NGINX_BIN || DEFAULT_NGINX;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--scratch" && args[i + 1]) scratch = resolve(args[i + 1]);
    else if (args[i] === "--listen" && args[i + 1]) listen = args[i + 1];
    else if (args[i] === "--nginx" && args[i + 1]) nginxBin = resolve(args[i + 1]);
  }

  const S = scratch;
  const www = join(S, "www");
  const logs = join(S, "logs");
  const certs = join(S, "certs");
  const releasesDir = join(www, "releases");
  const redirectsLive = join(www, "redirects.conf");
  const contentRoot = join(S, "contentroot");
  const candidateA = join(S, "candidate-redirects-A.conf");
  const candidateB = join(S, "candidate-redirects-B.conf");
  const candidateC = join(S, "candidate-redirects-C.conf");
  const conf = join(S, "drill-site.conf");
  const pidFile = join(logs, "nginx.pid");
  pidFileRef = () => pidFile; // R9/M2: identity check reaches this pid file
  const logFile = join(S, "drill.log");

  rmSync(S, { recursive: true, force: true });
  for (const d of [www, logs, certs, releasesDir, contentRoot]) mkdirSync(d, { recursive: true });
  cpSync(join(CERTS, "self-signed.crt"), join(certs, "self-signed.crt"));
  cpSync(join(CERTS, "self-signed.key"), join(certs, "self-signed.key"));

  const log = [];
  let reloads = 0;
  let startedMasterPid = 0; // set once nginx is up; fail() uses it to clean up
  const lines = (s) => log.push(s);
  const ok = (s) => lines(`[OK]   ${s}`);
  const stopNginx = () => {
    if (!startedMasterPid) return;
    try {
      // R9/M2: only ever signal a PID whose identity was verified against
      // THIS drill's pid file — never a recycled PID or another instance.
      if (!pidIsOurs(startedMasterPid)) {
        lines(`[cleanup] master ${startedMasterPid} identity no longer verifiable — not signalling`);
        startedMasterPid = 0;
        return;
      }
      const workersBeforeStop = workerPids(startedMasterPid);
      try {
        execFileSync(nginxBin, ["-s", "quit", "-c", conf], { stdio: "ignore" });
      } catch {
        process.kill(startedMasterPid, "SIGTERM");
      }
      // Wait for the master AND all recorded workers to actually exit (the
      // review required the process FAMILY, not just the master).
      const deadline = Date.now() + 5000;
      let masterGone = false;
      while (Date.now() < deadline) {
        let workersAlive = false;
        try {
          process.kill(startedMasterPid, 0);
        } catch {
          masterGone = true;
        }
        for (const w of workersBeforeStop) {
          try {
            process.kill(w, 0);
            workersAlive = true; // may be a recycled PID — identity-checked below
          } catch {}
        }
        // Re-verify surviving workers are still nginx workers of this master
        // (a recycled PID must not keep the drill waiting forever).
        const stillWorkers = masterGone ? workerPidsOfAny(workersBeforeStop) : [];
        if (masterGone && !workersAlive && stillWorkers.length === 0) return;
        if (masterGone && stillWorkers.length === 0 && !workersAlive) return;
        execFileSync("/bin/sh", ["-c", "sleep 0.05"], { stdio: "ignore" });
      }
      // Escalate ONLY after identity re-checks (never blind-kill).
      if (pidIsOurs(startedMasterPid, conf)) {
        try { process.kill(startedMasterPid, "SIGKILL"); } catch {}
      }
      for (const w of workerPidsOfAny(workersBeforeStop)) {
        try { process.kill(w, "SIGKILL"); } catch {}
      }
    } catch {
      // best-effort; residue scan below reports anything left
    }
  };
  /** Among `pids`, those still alive AND still running as nginx workers. */
  const workerPidsOfAny = (pids) => {
    const alive = [];
    for (const pid of pids) {
      try {
        process.kill(pid, 0);
        const out = execFileSync("/bin/ps", ["-p", String(pid), "-o", "command="], { encoding: "utf8" }).trim();
        if (/nginx: worker( process)?$/.test(out.trim())) alive.push(pid);
      } catch {}
    }
    return alive;
  };
  const residueScan = () => {
    try {
      // R8/M1 — REAL ps lines look like "12345 nginx: master process ...".
      // Match processes whose COMMAND (after the pid columns) starts with
      // "nginx:" — the pid/ppid columns were consumed by the split below.
      const out = execFileSync("/bin/ps", ["-axo", "pid=,ppid=,command="], { encoding: "utf8" });
      return out
        .split("\n")
        .map((l) => l.trim())
        .filter((l) => /^\d+\s+\d+\s+nginx:/.test(l) && (l.includes(conf) || l.includes(S)))
        .join("\n");
    } catch {
      return "(residue scan unavailable)";
    }
  };
  const fail = (s) => {
    lines(`[FAIL] ${s}`);
    stopNginx();
    const residue = residueScan();
    lines(
      `[cleanup] nginx stopped: ${startedMasterPid ? `master ${startedMasterPid} quit` : "not started"}; residue: ${residue || "none"}`,
    );
    console.log(log.join("\n"));
    writeFileSync(logFile, log.join("\n"));
    process.exitCode = 1;
  };
  globalThis.__drillCtx = { stopNginx };

  // =====================================================================
  // STEP 0 — derive the drill config from the delivered site.conf
  //          (--listen is FORWARDED — R8/M2)
  // =====================================================================
  lines(`[step0] deriving drill config from delivered template ${TEMPLATE}`);
  try {
    run("node", [
      DERIVE,
      "--template",
      TEMPLATE,
      "--out",
      conf,
      "--listen",
      listen,
      "--root",
      join(www, "current"),
      "--redirects",
      redirectsLive,
      "--pid",
      pidFile,
      "--error-log",
      join(logs, "error.log"),
      "--access-log",
      join(logs, "access.log"),
      "--certs-dir",
      certs,
    ]);
    lines(`[step0] derived config: ${conf} (sha256 ${fileSha256(conf)})`);
    if (!readFileSync(conf, "utf8").includes(`listen ${listen} ssl;`)) {
      return fail(`M2: --listen was NOT forwarded — derived config does not listen on ${listen}`);
    }
  } catch (e) {
    lines(`[step0] derivation FAILED: ${String((e && e.stderr) || e)}`);
    return fail("drill aborted — could not derive config from delivered template");
  }
  // Pre-first-activation state mirrors a host before the first redirect
  // publish: the include target does not exist yet, so nginx -t needs the
  // empty placeholder (same semantic as derive-drill-config --verify).
  writeFileSync(redirectsLive, "# empty — pre-first-redirect-publish placeholder\n");
  const derivedTest = run(nginxBin, ["-t", "-c", conf]);
  lines(`[step0] nginx -t (derived, empty redirects): ${derivedTest.split("\n")[0]}`);
  ok("delivered template derived + nginx -t (pre-activation) PASS");

  // =====================================================================
  // §3.3.1+2 — Generate candidate redirect configs WITH THE DELIVERED CLI
  //            (WP-12 validated, isolated content root) + verify 301
  //            targets resolve to REAL canonical pages in the release.
  // =====================================================================
  const contentDir = join(contentRoot, "content");
  mkdirSync(join(contentDir, "galleries", "g_ok"), { recursive: true });
  mkdirSync(join(contentDir, "galleries", "g_north"), { recursive: true });
  mkdirSync(join(contentDir, "galleries", "g_south"), { recursive: true });
  mkdirSync(join(contentDir, "galleries", "g_west"), { recursive: true });
  mkdirSync(join(contentDir, "places"), { recursive: true });
  const meta = (id, slug) => `id: ${id}\nslug: ${slug}\nstatus: published\n`;
  writeFileSync(join(contentDir, "galleries", "g_ok", "meta.yaml"), meta("g_ok", "ok-gallery"));
  writeFileSync(join(contentDir, "galleries", "g_north", "meta.yaml"), meta("g_north", "north"));
  writeFileSync(join(contentDir, "galleries", "g_south", "meta.yaml"), meta("g_south", "south"));
  writeFileSync(join(contentDir, "galleries", "g_west", "meta.yaml"), meta("g_west", "west"));
  writeFileSync(join(contentDir, "places", "plaza.yaml"), "id: pl_plaza\nslug: plaza\nregion: X\n");
  const writeRedirectsYaml = (entries) => {
    let y = "";
    for (const [from, target] of entries) y += `${from}:\n  ${target}\n`;
    writeFileSync(join(contentDir, "redirects.yaml"), y);
  };

  writeRedirectsYaml([["/old-a", "gallery_id: g_ok"]]);
  generateRedirectsViaCli(candidateA, contentRoot);
  writeRedirectsYaml([
    ["/old-north", "gallery_id: g_north"],
    ["/old-south", "gallery_id: g_south"],
    ["/old-west", "gallery_id: g_west"],
  ]);
  generateRedirectsViaCli(candidateB, contentRoot);
  writeRedirectsYaml([
    ["/old-north", "gallery_id: g_north"],
    ["/old-west", "gallery_id: g_west"],
  ]);
  generateRedirectsViaCli(candidateC, contentRoot);
  lines(
    `[§3.3.2] candidate hashes (delivered CLI): A=${fileSha256(candidateA)} B=${fileSha256(candidateB)} C=${fileSha256(candidateC)}`,
  );
  // The generated rules must be the delivered format (rewrite ... permanent;)
  // and come from the validated WP-12 resolution — the CLI fail-closes
  // otherwise (exit 1 from generateRedirectsViaCli aborts the drill).
  const bText = readFileSync(candidateB, "utf8");
  if (!bText.includes("rewrite ^/old-north$ /galleries/north permanent;")) {
    return fail("delivered CLI output does not contain the validated north rule");
  }
  ok("candidate redirect configs generated by the delivered redirects CLI (WP-12 validated)");

  // =====================================================================
  // §3.3.1/3/4/6 — first content publish (rel-A) + activate redirect A
  //                 via the SHARED deploy transaction
  // =====================================================================
  // rel-A carries REAL canonical pages (galleries/north|south|west) so the
  // 301→target verification proves the destination is servable content, not
  // just a Location string (R7 review finding).
  makeRelease(releasesDir, "rel-A", {
    "index.html": "<html>rel-A</html>",
    "galleries/ok-gallery/index.html": "<html>gallery ok (rel-A)</html>",
    "galleries/north/index.html": "<html>gallery north (rel-A)</html>",
    "galleries/south/index.html": "<html>gallery south (rel-A)</html>",
    "galleries/west/index.html": "<html>gallery west (rel-A)</html>",
  });
  const { runDeployTransaction } = await import("./deploy-transaction.mjs");

  // Smoke/verify helpers RETRY briefly: right after a reload signal a request
  // can still land on the draining OLD worker, so the expected behavior must
  // be given a short settle window before being judged failed.
  const mkProbe = (label, path, expectStatus, expectMarker) => async () => {
    const deadline = Date.now() + 2000;
    let r = curl(listen, path);
    while (Date.now() < deadline) {
      const okRes = r.status === expectStatus && (expectMarker === undefined || r.body.includes(expectMarker) || (expectStatus === 301 && r.location.includes(expectMarker)));
      if (okRes) return { ok: true, detail: `GET ${path} -> ${r.status} ${r.location || ""} ${r.body.length}B (want ${expectStatus}${expectMarker ? ` marker ${expectMarker}` : ""})${label}` };
      execFileSync("/bin/sh", ["-c", "sleep 0.05"], { stdio: "ignore" });
      r = curl(listen, path);
    }
    return { ok: false, detail: `GET ${path} -> ${r.status} ${r.location || ""} ${r.body.length}B (want ${expectStatus}${expectMarker ? ` marker ${expectMarker}` : ""})${label} — did not settle` };
  };
  const mkSmoke = (path, expectStatus, expectMarker) => mkProbe(" (post-activation smoke)", path, expectStatus, expectMarker);
  const mkVerify = (path, expectStatus, expectMarker) => mkProbe(" (restored previous state)", path, expectStatus, expectMarker);

  // start nginx as an independent local process (loopback, non-privileged)
  const port = listen.split(":")[1];
  const portInUse = execFileSync(
    "/bin/sh",
    ["-c", `lsof -iTCP:${port} -sTCP:LISTEN 2>/dev/null | grep -v COMMAND || true`],
    { encoding: "utf8" },
  ).trim();
  if (portInUse) {
    return fail(
      `port ${listen} already in use — a previous nginx instance may be running:\n${portInUse}`,
    );
  }
  const nginxProc = spawn(nginxBin, ["-c", conf], { stdio: ["ignore", "ignore", "pipe"] });
  nginxProc.on("error", (e) => fail(`nginx spawn error: ${String(e)}`));
  const masterPid = await new Promise((res, rej) => {
    const start = Date.now();
    const poll = () => {
      if (existsSync(pidFile)) {
        const pid = Number(readFileSync(pidFile, "utf8").trim());
        if (pid > 0) return res(pid);
      }
      if (Date.now() - start > 5000) {
        const errLog = existsSync(join(logs, "error.log"))
          ? readFileSync(join(logs, "error.log"), "utf8").trim()
          : "(no error log)";
        return rej(new Error(`nginx pid file timeout; error log tail: ${errLog.slice(-300)}`));
      }
      setTimeout(poll, 50);
    };
    poll();
  });
  startedMasterPid = masterPid;
  lines(`[nginx] master pid ${masterPid}`);
  ok(`nginx started (pid ${masterPid}, ${listen})`);

  // First publish: activate redirect A TOGETHER with rel-A in one transaction.
  let tx = await runDeployTransaction({
    root: www,
    release: join(releasesDir, "rel-A"),
    candidateRedirects: candidateA,
    liveRedirects: redirectsLive,
    nginxConf: conf,
    nginxBin,
    smoke: mkSmoke("/old-a", 301, "/galleries/ok-gallery"),
    verifySmoke: mkVerify("/old-a", 301, "/galleries/ok-gallery"),
  });
  lines(`[§3.3.4] first publish transaction:\n${tx.steps.map((s) => `    ${s}`).join("\n")}`);
  if (!tx.ok) return fail(`first publish transaction failed: ${tx.error}`);
  reloads += 1; // A activation reloaded (first redirect activation)


  // Post-transaction observations use the SAME settle-aware polling as the
  // reload race elsewhere in this drill: a request issued right after the
  // reload signal can still land on the draining OLD worker (observed live
  // as a spurious 404 for /old-a), so the expected behavior must be given a
  // short settle window before being judged failed.
  let r = waitForBehavior(listen, "/", 200);
  lines(`[§3.3.6] GET / -> ${r.status} ${r.body.length}B`);
  if (r.status !== 200 || !r.body.includes("rel-A")) return fail("rel-A content smoke failed");
  // 301 → REAL canonical page (content exists in the release and serves 200).
  r = waitForBehavior(listen, "/old-a", 301);
  if (r.status !== 301 || !r.location.includes("/galleries/ok-gallery")) {
    return fail(`redirect A smoke failed (got ${r.status} ${r.location})`);
  }
  const target = followToContent(listen, locPath(r.location));
  lines(`[§3.3.6] GET /old-a -> 301 ${r.location} -> ... -> ${target.status} ${target.body.length}B`);
  if (target.status !== 200 || !target.body.includes("rel-A")) {
    return fail("301 target /galleries/ok-gallery is not a servable canonical page (R7 finding)");
  }
  ok("redirect A 301 → target canonical page serves 200 with real content");

  // =====================================================================
  // §3.3.5 — content-only release rel-B: switch WITHOUT reload
  // =====================================================================
  makeRelease(releasesDir, "rel-B", {
    "index.html": "<html>rel-B</html>",
    "galleries/ok-gallery/index.html": "<html>gallery ok (rel-B)</html>",
    "galleries/north/index.html": "<html>gallery north (rel-B)</html>",
    "galleries/south/index.html": "<html>gallery south (rel-B)</html>",
    "galleries/west/index.html": "<html>gallery west (rel-B)</html>",
  });
  const workersBefore = workerPids(masterPid);
  lines(`[§3.3.5] worker set before content-only switch: ${workersBefore.join(",") || "(none observed)"}`);
  tx = await runDeployTransaction({
    root: www,
    release: join(releasesDir, "rel-B"),
    // content-only: no candidateRedirects → no include change, NO reload.
    liveRedirects: redirectsLive,
    nginxConf: conf,
    nginxBin,
    smoke: mkSmoke("/", 200, "rel-B"),
  });
  lines(`[§3.3.5] content-only rel-B transaction:\n${tx.steps.map((s) => `    ${s}`).join("\n")}`);
  if (!tx.ok) return fail(`content-only transaction failed: ${tx.error}`);
  if (tx.steps.some((s) => s.startsWith("reload: OK") || s.startsWith("reload: FAILED"))) {
    return fail("content-only release triggered a reload (transaction reloaded despite content-only contract)");
  }
  const workersAfter = workerPids(masterPid);
  lines(`[§3.3.5] worker set after content-only switch: ${workersAfter.join(",") || "(none observed)"}`);
  // R9/M2: the content-only contract is asserted, not just printed — the
  // worker SET (master's children) must be IDENTICAL before/after the switch.
  if (JSON.stringify([...workersBefore].sort()) !== JSON.stringify([...workersAfter].sort())) {
    return fail(`content-only release changed the worker set (before: ${workersBefore.join(",") || "-"} after: ${workersAfter.join(",") || "-"}) — a reload happened where §3.3.5 forbids one`);
  }
  r = waitForBehavior(listen, "/", 200);
  if (r.status !== 200 || !r.body.includes("rel-B")) return fail("rel-B content smoke failed");
  ok(`content-only release: worker set unchanged [${workersBefore.join(",") || "-"}] (asserted), new content served`);

  // =====================================================================
  // §3.3.3-6 — redirect update B: transaction (candidate -t → activate →
  //            reload → 301 → REAL target page)
  // =====================================================================
  tx = await runDeployTransaction({
    root: www,
    release: join(releasesDir, "rel-B"), // content unchanged; config change only
    candidateRedirects: candidateB,
    liveRedirects: redirectsLive,
    nginxConf: conf,
    nginxBin,
    smoke: mkSmoke("/old-west", 301, "/galleries/west"),
    verifySmoke: mkVerify("/old-west", 301, "/galleries/west"),
  });
  lines(`[§3.3.3-4] redirect B transaction:\n${tx.steps.map((s) => `    ${s}`).join("\n")}`);
  if (!tx.ok) return fail(`redirect B transaction failed: ${tx.error}`);
  reloads += 1;
  r = waitForBehavior(listen, "/old-west", 301);
  lines(`[§3.3.6] GET /old-west -> ${r.status} ${r.location || "(no location)"} (after reload settled)`);
  if (r.status !== 301 || !r.location.includes("/galleries/west")) {
    return fail("redirect B smoke failed (expected 301 -> /galleries/west)");
  }
  const west = followToContent(listen, locPath(r.location));
  if (west.status !== 200 || !west.body.includes("rel-B")) {
    return fail("301 target /galleries/west does not serve the live release (target page verification)");
  }
  ok("redirect update: candidate -t + reload + 301 → real canonical page PASS");

  // =====================================================================
  // §3.3.7 — coupled rollback via the SHARED transaction: C fails smoke,
  //          previous release + redirects restored, recovery verified.
  //          This exercises the transaction's own rollback (no drill-side
  //          recovery code at all).
  // =====================================================================
  makeRelease(releasesDir, "rel-C", {
    "index.html": "<html>rel-C (broken — missing expected marker)</html>",
    "galleries/north/index.html": "<html>gallery north (rel-C)</html>",
    "galleries/west/index.html": "<html>gallery west (rel-C)</html>",
  });
  // rel-C is deliberately broken: the smoke demands marker "rel-C-ok" which
  // rel-C does not carry — the transaction must fail the smoke and roll back.
  tx = await runDeployTransaction({
    root: www,
    release: join(releasesDir, "rel-C"),
    candidateRedirects: candidateC,
    liveRedirects: redirectsLive,
    nginxConf: conf,
    nginxBin,
    smoke: mkSmoke("/", 200, "rel-C-ok"),
    verifySmoke: mkVerify("/old-south", 301, "/galleries/south"),
  });
  lines(`[§3.3.7] C transaction (deliberate smoke failure):\n${tx.steps.map((s) => `    ${s}`).join("\n")}`);
  if (tx.ok) return fail("drill contract: broken C was activated successfully — rollback path not exercised");
  if (!tx.rolledBack) return fail(`C activation failed but the transaction did NOT roll back: ${tx.error}`);
  reloads += 2; // C activation reload + rollback reload

  // Post-rollback verification (independent of the transaction's own checks):
  // old release content + old 301 + no rel-C leakage, settled after reload.
  const rr = waitForBehavior(listen, "/old-south", 301);
  r = curl(listen, "/");
  lines(`[post-rollback] GET / -> ${r.status} ${r.body.length}B`);
  lines(`[post-rollback] GET /old-south -> ${rr.status} ${rr.location || "(no location)"}`);
  const south = rr.status === 301 ? followToContent(listen, locPath(rr.location)) : { status: 0, body: "" };
  lines(`[post-rollback] GET ${rr.location || "-"} -> ${south.status} ${south.body.length}B`);
  const contentOk = r.status === 200 && r.body.includes("rel-B");
  const redirectOk = rr.status === 301 && rr.location.includes("/galleries/south") && south.status === 200 && south.body.includes("rel-B");
  const noC = !r.body.includes("rel-C");
  if (contentOk && redirectOk && noC) {
    ok("coupled rollback verified: old release content + old 301 (→ real page) + no rel-C leakage");
  } else {
    return fail(
      `coupled rollback verification FAILED (contentOk=${contentOk} redirectOk=${redirectOk} noC=${noC})`,
    );
  }

  // =====================================================================
  // STEP 7 — shutdown + residue check (R8/M1: real ps-line matching)
  // =====================================================================
  stopNginx();
  lines(`[step7] instance stopped (master ${startedMasterPid}); reloads=${reloads}`);
  const residue = residueScan();
  lines(`[step7] residue scan: ${residue || "no nginx processes referencing drill conf"}`);
  if (residue) return fail("nginx residue found after shutdown");
  // R9/M2: after cleanup, actually check the drill's own listen port for a
  // listener (lsof -t; empty output = nothing is listening on this port).
  const portAfter = execFileSync(
    "/bin/sh",
    ["-c", `lsof -tiTCP:${port} -sTCP:LISTEN 2>/dev/null || true`],
    { encoding: "utf8" },
  ).trim();
  lines(`[step7] port ${port} listener check after cleanup: ${portAfter || "none"}`);
  if (portAfter) {
    return fail(`port ${port} still has a listener after cleanup (pids: ${portAfter})`);
  }
  ok("nginx instance stopped; no residue; drill port free");

  // ---- final evidence summary ------------------------------------------
  lines("");
  lines("[evidence] current pointers: rel-A -> rel-B -> rel-C (broken, rolled back) -> rel-B");
  lines(
    `[evidence] redirect hashes: A=${fileSha256(candidateA)} B=${fileSha256(candidateB)} C=${fileSha256(candidateC)} live(rollback)=${fileSha256(redirectsLive)}`,
  );
  lines(
    `[evidence] reload count: ${reloads} (A activation: 1; content-only: 0; B: 1; C+rollback: 2)`,
  );
  lines(
    "[evidence] HTTP statuses: rel-A 200, A 301→page 200, rel-B 200 (no reload), B 301→page 200, C smoke FAIL → rollback 200 + old 301→page 200",
  );
  lines("[evidence] drill PASS");

  console.log(log.join("\n"));
  writeFileSync(logFile, log.join("\n"));
}

if (process.argv[1] && process.argv[1].endsWith("nginx-coupled-rollback-drill.mjs")) {
  main().catch((e) => {
    // Any unhandled failure must still stop the drill's nginx instance —
    // never leave a stray worker behind.
    try {
      if (globalThis.__drillCtx && typeof globalThis.__drillCtx.stopNginx === "function") {
        globalThis.__drillCtx.stopNginx();
      }
    } catch {}
    console.error(String((e && e.stack) || e));
    process.exitCode = 1;
  });
}
