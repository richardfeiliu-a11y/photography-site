#!/usr/bin/env node
// scripts/backup/create-backup.mjs — WP-56: client-side encrypted backup.
//
// Usage:
//   BACKUP_PASSPHRASE=... node scripts/backup/create-backup.mjs --out /path/to/backup-<id>
//
// The script (R7 directory protocol, 裁定③):
//   1. Collects non-rebuildable data: media/ingest-masters/, media fixtures,
//      content/ (authored YAML + redirects), deploy/env/.env.example.
//   2. Packs them into a tar archive inside an exclusive staging dir (0700).
//   3. Encrypts the tar with AES-256-GCM (Node crypto; OpenSSL 3.x `enc`
//      rejects AEAD ciphers, so the client-side cipher runs in-process).
//      File layout: [iv 12B][ciphertext...][tag 16B] — the tag is appended by
//      the sink's final() because GCM only reveals the auth tag at stream end.
//   4. Writes an integrity manifest (backupFormat "dir-v1") and removes the
//      plaintext tar, then atomically renames the WHOLE staging dir to --out.
//      A backup is only ever visible fully-formed (ciphertext + manifest
//      together); a failure cleans ONLY this run's staging dir and never
//      touches a previous backup at --out (final target must not exist).
//
// Non-production drill: writes only the staging dir and the final --out dir;
// never touches real credentials.
import { createCipheriv, createHash, randomBytes } from "node:crypto";
import {
  closeSync,
  constants as fsConstants,
  createReadStream,
  existsSync,
  mkdirSync,
  openSync,
  renameSync,
  rmSync,
  statSync,
  writeFileSync,
  writeSync,
} from "node:fs";
import { Writable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const ENC_FLAGS = fsConstants.O_CREAT | fsConstants.O_EXCL | fsConstants.O_WRONLY;
const ENC_MODE = 0o600;

const ROOT = resolve(join(fileURLToPath(import.meta.url), "..", "..", ".."));

/** Manifest fields that identify the container format, asserted by restore tooling. */
const BACKUP_FORMAT = "dir-v1";

/**
 * Non-rebuildable sources. dist/ generated/ releases/ are rebuildable and
 * excluded (BACKUP_AND_RECOVERY §4.5).
 *
 * R8/M4 — the list is aligned with the rebuildability contract:
 *   - media/ingest-masters — WEB INGEST MASTERS (§3.1): the canonical
 *     off-site backup payload.
 *   - media/stage3c-fixtures — the FROZEN 113-file corpus
 *     (REAL_PHOTO_FIXTURE_MANIFEST.md): gitignored working copy on the VPS,
 *     NOT rebuildable from the repo, so it is backed up. Retained here with
 *     that purpose recorded.
 *   - media/wp16-icc-fixtures — REMOVED: reproducible documentation copies
 *     regenerated by `npm run bench:wp16:fixtures` (scripts/bench/icc/
 *     make-fixtures.ts). Regenerable output must not masquerade as
 *     non-rebuildable data (it also re-derives from stage3c-fixtures, which
 *     IS backed up).
 *   - content/ — authored YAML + redirects: Git is the version-controlled
 *     authority, the copy in the backup is a point-in-time safety net for
 *     the restore reconciliation step (RESTORE-DRILL §4, R8/I7).
 *   - deploy/env/.env.example — placeholder template, no real values.
 */
const BACKUP_SOURCES = [
  "media/ingest-masters",
  "media/stage3c-fixtures",
  "content",
  "deploy/env/.env.example",
];

/** Rebuildable outputs never enter a backup, regardless of --sources. */
const EXCLUDE_PATTERNS = ["dist", "generated", "releases", "node_modules"];

function fail(message) {
  console.error(`[create-backup] ${message}`);
  process.exitCode = 1;
}

/** sha256 of a file, streamed. */
function hashFile(path) {
  return new Promise((res, rej) => {
    const hash = createHash("sha256");
    createReadStream(path)
      .on("data", (c) => hash.update(c))
      .on("end", () => res(hash.digest("hex")))
      .on("error", rej);
  });
}

/** Unpredictable, exclusively-named staging dir inside parent (0700). */
function uniqueStagingDir(parent) {
  const hex = createHash("sha256").update(randomBytes(8)).digest("hex").slice(0, 16);
  return join(parent, `.backup-${hex}.${process.pid}.tmp`);
}

/**
 * AES-256-GCM encrypt a file into an EXCLUSIVELY created dst file, layout
 * [iv 12B][ciphertext][tag 16B]. iv is written via the open fd before the
 * pipeline; the tag is appended by the sink's final() (GCM reveals the auth
 * tag only after cipher.final(), which the pipeline runs before the sink
 * finalizes). pipeline() wires reader -> cipher -> writer from the start, so
 * every stream error and backpressure propagates from creation — the R7
 * root cause (writer errors only observed after reader 'end') cannot recur:
 * errors originate inside pipeline() and are rejected/awaited by the caller.
 */
async function encryptFile(src, dst, passphrase) {
  const key = createHash("sha256").update(passphrase).digest(); // 32-byte key from passphrase
  const iv = randomBytes(12);
  const encFd = openSync(dst, ENC_FLAGS, ENC_MODE); // O_CREAT|O_EXCL, 0600

  try {
    const cipher = createCipheriv("aes-256-gcm", key, iv);
    writeAll(encFd, iv);
    const sink = new Writable({
      write(chunk, _enc, callback) {
        try {
          if (!Buffer.isBuffer(chunk)) chunk = Buffer.from(chunk);
          void _enc;
          writeAll(encFd, chunk);
          callback();
        } catch (e) {
          callback(e);
        }
      },
      final(callback) {
        try {
          // cipher.final() already ran (pipeline finalized cipher before
          // sink); the GCM auth tag is only available now — append it end.
          writeAll(encFd, cipher.getAuthTag());
          callback();
        } catch (e) {
          callback(e);
        }
      },
    });
    await pipeline(createReadStream(src), cipher, sink);
  } finally {
    try {
      closeSync(encFd);
    } catch (e) {
      // already closed by the write-stream teardown — nothing to do.
      void e;
    }
  }
}

/** Write an entire chunk to an fd, looping over partial writeSync results. */
function writeAll(fd, chunk) {
  const buf = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk);
  let offset = 0;
  while (offset < buf.length) {
    const n = writeSync(fd, buf, offset, buf.length - offset);
    if (n === 0) throw new Error("zero-byte write to encrypted backup");
    offset += n;
  }
}

async function buildManifest(staging, passphrase, sources, rawSha, encSha) {
  const keyFingerprint = createHash("sha256").update(passphrase).digest("hex").slice(0, 12);
  const manifest = {
    tool: "create-backup.mjs",
    backupFormat: BACKUP_FORMAT,
    createdAt: new Date().toISOString(),
    cipher: "aes-256-gcm",
    layout: "[iv 12B][ciphertext][tag 16B]",
    sources,
    keyFingerprint,
    tarSha256: rawSha,
    encSha256: encSha,
    encBytes: statSync(join(staging, "archive.enc")).size,
  };
  // 0600 explicit + openSync O_EXCL semantics via writeFileSync flag "wx".
  writeFileSync(join(staging, "manifest.json"), JSON.stringify(manifest, null, 2), {
    mode: 0o600,
    flag: "wx",
  });
  return manifest;
}

async function run(out, passphrase, sources) {
  // 1. Verify all sources exist.
  for (const src of sources) {
    if (!existsSync(join(ROOT, src))) {
      fail(`source missing: ${src}`);
      return 1;
    }
  }

  // 2. The final backup dir must NOT exist — never overwrite a previous backup.
  if (existsSync(out)) {
    fail(`target backup path already exists: ${out}（不覆盖上一份备份）`);
    return 1;
  }

  // 3. Exclusive staging dir (0700) next to --out; everything lands inside it.
  const parent = resolve(join(out, ".."));
  const staging = uniqueStagingDir(parent);
  mkdirSync(staging, { mode: 0o700 });

  try {
    // 4. tar the sources to staging/archive.tar.
    // COPYFILE_DISABLE=1 suppresses macOS AppleDouble (._*) and xattr metadata
    // from the archive so the backup is clean when restored cross-platform.
    // EXCLUDE_PATTERNS keep rebuildable output out of every backup.
    const tempTar = join(staging, "archive.tar");
    const tarArgs = ["-cf", tempTar];
    // Options must precede the "--" end-of-options marker.
    for (const pat of EXCLUDE_PATTERNS) tarArgs.push("--exclude", pat);
    tarArgs.push("--");
    for (const src of sources) tarArgs.push(src);
    execFileSync("tar", tarArgs, {
      cwd: ROOT,
      stdio: "pipe",
      env: { ...process.env, COPYFILE_DISABLE: "1" },
    });

    // 5. Encrypt staging/archive.tar -> staging/archive.enc (exclusive, 0600).
    await encryptFile(tempTar, join(staging, "archive.enc"), passphrase);

    // 6. Integrity manifest + remove the plaintext tar (plaintext only ever
    //    exists inside the staging dir, and only for the duration of a run).
    const rawSha = await hashFile(tempTar);
    const encSha = await hashFile(join(staging, "archive.enc"));
    await buildManifest(staging, passphrase, sources, rawSha, encSha);
    rmSync(tempTar, { force: true });

    // 7. Verify BOTH deliverables are complete before publishing — never a
    //    ciphertext-first / manifest-later pair.
    const encPath = join(staging, "archive.enc");
    const manifestPath = join(staging, "manifest.json");
    if (!existsSync(encPath) || !existsSync(manifestPath)) {
      fail("staging incomplete; not published");
      return 1;
    }

    // 8. Atomic publish: same-filesystem directory rename.
    renameSync(staging, out); // after this, staging no longer exists

    console.log(`[create-backup] encrypted backup written: ${out}`);
    console.log(`[create-backup] manifest: ${join(out, "manifest.json")}`);
    console.log(`[create-backup] enc sha256 ${encSha.slice(0, 16)}…`);
    return 0;
  } finally {
    // Failure cleanup touches ONLY this run's staging dir; a previous backup
    // at --out is never in scope (existsSync(out) check happens up-front).
    rmSync(staging, { recursive: true, force: true });
  }
}

async function main() {
  const args = process.argv.slice(2);
  let out = null;
  let sources = BACKUP_SOURCES;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--out" && args[i + 1]) out = resolve(args[i + 1]);
    if (args[i] === "--sources" && args[i + 1]) sources = args[i + 1].split(",").filter(Boolean);
  }
  let passphrase = process.env.BACKUP_PASSPHRASE ?? null;
  if (!passphrase && args.includes("--passphrase")) {
    const i = args.indexOf("--passphrase");
    passphrase = args[i + 1] ?? null;
  }
  if (!out || !passphrase) {
    fail("usage: node scripts/backup/create-backup.mjs --out <backup-dir> [--passphrase <key>] [--sources a,b,c] (or BACKUP_PASSPHRASE env)");
    return;
  }
  if (passphrase.length < 8) {
    fail("passphrase must be at least 8 characters");
    return;
  }
  try {
    const code = await run(out, passphrase, sources);
    if (code !== 0) process.exitCode = code;
  } catch (e) {
    fail(`backup failed: ${String((e && e.stack) || e)}`);
  }
}

main();