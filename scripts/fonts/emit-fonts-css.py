#!/usr/bin/env python3
"""WP-05 fonts.css emitter — generates src/styles/fonts.css from the SERVED
font files, deriving every unicode-range from the file's ACTUAL cmap
(PERFORMANCE_BUDGET §7.5: "Do not claim a unicode-range broader than the
actual served subset"). Ranges are honest by construction; regenerate after
any font change:

    .venv/bin/python scripts/fonts/emit-fonts-css.py > src/styles/fonts.css

Faces emitted (PoC weight policy derived from FINAL_DESIGN_SPECIFICATION
§2.2 role table; SC weight gaps are a documented PoC limitation):
  Source Serif 4  400, 500        (Latin; 500 instanced from the 4.005R VF)
  Source Sans 3   400, 500, 600   (Latin)
  Noto Serif SC   400 (PoC min)   (Option A broad static subset)
  Noto Sans SC    400 (PoC min)   (Option A broad static subset)

font-display: optional everywhere (§7.2, frozen G1). No preload (§7.5:
preload only proven above-fold fonts — the PoC proves none).
"""

import sys
from pathlib import Path

from fontTools.ttLib import TTFont

REPO = Path(__file__).resolve().parents[2]
PUBLIC = REPO / "public"

# (family, weight, path under public/, kind)
FACES = [
    ("Source Serif 4", 400, "fonts/source-serif-4/source-serif-4-latin-400.a6588786.woff2", "latin"),
    ("Source Serif 4", 500, "fonts/source-serif-4/source-serif-4-latin-500.466650a4.woff2", "latin"),
    ("Source Sans 3", 400, "fonts/source-sans-3/source-sans-3-latin-400.37a5ca73.woff2", "latin"),
    ("Source Sans 3", 500, "fonts/source-sans-3/source-sans-3-latin-500.2e432563.woff2", "latin"),
    ("Source Sans 3", 600, "fonts/source-sans-3/source-sans-3-latin-600.3b487916.woff2", "latin"),
    ("Noto Serif SC", 400, "fonts/noto-serif-sc/noto-serif-sc-sc400-option-b.woff2", "sc"),
    ("Noto Sans SC", 400, "fonts/noto-sans-sc/noto-sans-sc-sc400-option-b.woff2", "sc"),
]


def unicode_ranges(path):
    points = sorted(TTFont(path).getBestCmap().keys())
    ranges = []
    for cp in points:
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return ", ".join(f"U+{lo:04X}" if lo == hi else f"U+{lo:04X}-{hi:04X}" for lo, hi in ranges)


def main(out):
    out.write(
        "/*\n"
        " * src/styles/fonts.css — GENERATED by scripts/fonts/emit-fonts-css.py\n"
        " * (WP-05). Do not edit unicode-range values by hand: each range is\n"
        " * derived from the actual cmap of the served file, per\n"
        " * research/production-architecture/PERFORMANCE_BUDGET.md §7.5 (never\n"
        " * claim a range broader than the served subset). Regenerate with:\n"
        " *\n"
        " *   .venv/bin/python scripts/fonts/emit-fonts-css.py > src/styles/fonts.css\n"
        " *\n"
        " * font-display: optional everywhere (§7.2, frozen G1). No font preload\n"
        " * (§7.5: preload only proven above-fold fonts — the PoC proves none).\n"
        " * Served CJK faces are the Option B build-derived subsets (unicodes\n"
        " * scanned from content/ + tests/fixtures/content/ + the documented\n"
        " * fallback ranges from PERFORMANCE_BUDGET §7.4); the OTF source is\n"
        " * github.com/notofonts/noto-cjk/releases/tag/{Serif2.003,Sans2.004}\n"
        " * and the subset is regenerated by scripts/fonts/subset-poc.mjs.\n"
        " * Strategy verdict and WP-46 follow-up live in docs/implementation/WP-05.md.\n"
        " */\n\n"
    )
    for family, weight, rel, kind in FACES:
        path = PUBLIC / rel
        if not path.exists():
            sys.exit(f"missing served font: {rel} (run the subsetting pipeline first)")
        rng = unicode_ranges(path)
        out.write(f"/* {family} {weight} — {kind} subset, upstream-derived */\n")
        out.write("@font-face {\n")
        out.write(f'  font-family: "{family}";\n')
        out.write("  font-style: normal;\n")
        out.write(f"  font-weight: {weight};\n")
        out.write("  font-display: optional;\n")
        out.write(f'  src: url("/{rel}") format("woff2");\n')
        out.write(f"  unicode-range: {rng};\n")
        out.write("}\n\n")


if __name__ == "__main__":
    main(sys.stdout)
