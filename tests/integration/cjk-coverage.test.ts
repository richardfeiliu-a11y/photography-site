import { describe, expect, test } from "vitest";
import { expandRangeToken } from "../../scripts/fonts/coverage.mjs";
describe("WP-46 range expansion", () => {
  test("single and range tokens expand exactly", () => {
    expect(expandRangeToken("U+3002")).toEqual([0x3002, 0x3002]);
    expect(expandRangeToken("U+4E00-4E02")).toEqual([0x4e00, 0x4e02]);
  });
});
import { parseCssFaces } from "../../scripts/fonts/coverage.mjs";
const CSS = [
  "@font-face {",
  "  src: url(/fonts/a.woff2);",
  "  unicode-range: U+4E00-4E02, U+3002;",
  "}",
  "@font-face {",
  "  src: url(/fonts/b.woff2);",
  "  unicode-range: U+0020-007E;",
  "}",
  "",
].join(String.fromCharCode(10));
describe("WP-46 css face parsing", () => {
  test("faces parse to per-file range sets", () => {
    const faces = parseCssFaces(CSS);
    expect(faces).toHaveLength(2);
    const sc = faces.find((f) => f.file.indexOf("a.woff2") >= 0);
    expect(sc && sc.ranges.has(0x4e00)).toBe(true);
    expect(sc && sc.ranges.has(0x4e03)).toBe(false);
  });
});
import { load as parseYaml } from "js-yaml";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { checkCoverage, collectCodepoints } from "../../scripts/fonts/coverage.mjs";
const TENG = String.fromCharCode(0x6ed5, 0x738b, 0x9601);
const ARROW = String.fromCharCode(0x2192);
const ZHE = String.fromCharCode(0x5586);
describe("WP-46 corpus collection", () => {
  test("values collected, comment-only glyphs excluded", () => {
    const text = ["title: " + TENG, "# arrow " + ARROW + " never renders", "note: plain", ""].join(
      String.fromCharCode(10),
    );
    const docs = parseYaml(text);
    const found = collectCodepoints(Array.isArray(docs) ? docs : [docs], "probe");
    expect(found.has(0x6ed5)).toBe(true);
    expect(found.has(0x2192)).toBe(false);
  });
});
describe("WP-46 coverage decision", () => {
  test("outside character detected with codepoint", () => {
    const result = checkCoverage({ docs: [{ caption: ZHE }], cssText: CSS, allowlist: new Set() });
    expect(result.uncovered.map((u) => u.hex)).toEqual(["U+5586"]);
  });
  test("allowlisted characters pass as accepted fallback", () => {
    const result = checkCoverage({
      docs: [{ caption: ZHE }],
      cssText: CSS,
      allowlist: new Set([0x5586]),
    });
    expect(result.uncovered).toEqual([]);
    expect(result.accepted).toEqual(["U+5586"]);
  });
  test("served css is generator-marked", () => {
    const root = new URL("../../", import.meta.url).pathname;
    const css = readFileSync(join(root, "src", "styles", "fonts.css"), "utf8");
    expect(css.indexOf("GENERATED by scripts/fonts/emit-fonts-css.py") >= 0).toBe(true);
  });
});
