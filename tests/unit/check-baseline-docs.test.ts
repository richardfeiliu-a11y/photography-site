// R2 — check-baseline-docs reconciliation (RED first).
import { describe, expect, test } from "vitest";
import { applyManagedTable, reconcile } from "../../scripts/perf/check-baseline-docs.mjs";

const LCP_MARKER = "<!-- GENERATED by check-baseline-docs: LCP medians by page/profile -->";

function baseBaseline(): any {
  return {
    version: 2,
    measuredAt: "2026-09-06T22:00:00.000Z",
    pages: [
      {
        path: "/",
        profiles: {
          desktop: { lcp: { medianMs: 840 } },
          mobileLowEnd: { lcp: { medianMs: 3508 } },
        },
      },
      {
        path: "/galleries/long-gallery-72",
        profiles: {
          desktop: { lcp: { medianMs: 3832 } },
          mobileLowEnd: { lcp: { medianMs: 1800 } },
        },
      },
    ],
  };
}

function inSyncDecision(baseline: any) {
  const lines = baseline.pages
    .map((p: any) => {
      const d = p.profiles.desktop.lcp.medianMs;
      const m = p.profiles.mobileLowEnd.lcp.medianMs;
      const mark = d > 2500 || m > 2500 ? " ⚠" : "";
      return `| ${p.path} | ${d} | ${m} |${mark}|`;
    })
    .join("\n");
  return [
    `# Heading`,
    ``,
    `run: ${baseline.measuredAt}`,
    ``,
    `${LCP_MARKER}`,
    ``,
    `| page | desktop LCP ms | mobileLowEnd LCP ms | notes |`,
    `|---|---|---|---|`,
    lines,
    ``,
    `## Other Section`,
  ].join("\n");
}

describe("reconcile()", () => {
  test("no drift when the decision doc mirrors the canonical JSON", () => {
    const baseline = baseBaseline();
    const md = inSyncDecision(baseline);
    const { drift } = reconcile(baseline, md);
    expect(drift).toEqual([]);
  });

  test("LCP table drift is detected when the JSON changes", () => {
    const baseline = baseBaseline();
    const md = inSyncDecision(baseline).replace("3508", "3700");
    const { drift } = reconcile(baseline, md);
    expect(drift.some((d) => d.kind === "lcp-table")).toBe(true);
  });

  test("run-id drift is detected when measuredAt is missing from the doc", () => {
    const baseline = baseBaseline();
    const md = "# Heading\n\n## Some section, no measuredAt mentioned";
    const { drift } = reconcile(baseline, md);
    expect(drift.some((d) => d.kind === "run-id")).toBe(true);
  });

  test("known LCP red items are marked in the managed table", () => {
    const baseline = baseBaseline();
    const { table } = reconcile(baseline, "");
    expect(table).toContain("⚠");
    expect(table).toContain("| / | 840 | 3508 |");
    expect(table).toContain(
      "| /galleries/long-gallery-72 | 3832 | 1800 |",
    );
  });

  test("known LCP red items are marked in the managed table", () => {
    const baseline = baseBaseline();
    const { table } = reconcile(baseline, "");
    expect(table).toContain("⚠");
    expect(table).toContain("| / | 840 | 3508 |");
    expect(table).toContain(
      "| /galleries/long-gallery-72 | 3832 | 1800 |",
    );
  });
});

describe("applyManagedTable() — the --write path", () => {
  test("replaces the stale table when the managed block ends the document", () => {
    // Regression (found 2026-09-15 while promoting the R4 baseline): the
    // previous `m`-flagged regex let `$` match end-of-LINE, so --write appended
    // a second table to the real doc instead of replacing the stale one.
    const baseline = baseBaseline();
    const { table } = reconcile(baseline, "");
    const doc = [
      "# PERFORMANCE-BASELINE",
      "",
      `Run id: ${baseline.measuredAt}`,
      "",
      `${LCP_MARKER}`,
      "",
      "| page | desktop LCP ms | mobileLowEnd LCP ms | notes |",
      "|---|---|---|---|",
      "| /stale/page | 9999 | 9999 | ⚠|",
      "", // trailing blank line: the stale block is the last content
    ].join("\n");
    const next = applyManagedTable(doc, table);
    expect(next.match(/GENERATED by check-baseline-docs/g)).toHaveLength(1);
    expect(next).not.toContain("9999");
    expect(next).not.toContain("/stale/page");
    // And the result must satisfy the check side of the same tool.
    expect(reconcile(baseline, next).drift).toEqual([]);
  });

  test("is idempotent — writing twice yields the same document", () => {
    const baseline = baseBaseline();
    const { table } = reconcile(baseline, "");
    const once = applyManagedTable(inSyncDecision(baseline), table);
    const twice = applyManagedTable(once, table);
    expect(twice).toBe(once);
  });

  test("keeps following sections intact when the block is not last", () => {
    const baseline = baseBaseline();
    const { table } = reconcile(baseline, "");
    const next = applyManagedTable(inSyncDecision(baseline).replace("840", "1"), table);
    expect(next).toContain("## Other Section");
    expect(next.match(/GENERATED by check-baseline-docs/g)).toHaveLength(1);
    expect(reconcile(baseline, next).drift).toEqual([]);
  });
});
